def build_edition(edition: str, skip_tests: bool) -> Path:
    py = DEFAULT_PYTHON[edition]
    if not py.exists():
        sys.exit(f"Missing {py}. Create the venv for the {edition} edition first (see README).")
    dist = build(edition, py, skip_tests)
    (dist / "README.txt").write_text(README.format(
        v=APP_VERSION, repo=REPO, ed_title=" (NVIDIA GPU edition)" if edition == "gpu" else "",
        ed_text=ED_TEXT[edition]), encoding="utf-8")
    return dist


# --- packaging ---------------------------------------------------------------------------
def make_zip(edition: str) -> list[Path]:
    dist = dist_dir(edition)
    zpath = OUT / name(edition, "win64-portable.zip")
    files = sorted(p for p in dist.rglob("*") if p.is_file())
    print(f"Zipping {edition}: {len(files)} files ({sum(p.stat().st_size for p in files) / 1e9:.2f} GB)", flush=True)
    with zipfile.ZipFile(zpath, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6, allowZip64=True) as z:
        for p in files:
            z.write(p, Path("VoiceCleaner") / p.relative_to(dist))
    if zpath.stat().st_size <= PART_SIZE:
        return [zpath]
    return split_file(zpath)


def split_file(path: Path) -> list[Path]:
    """Raw byte split (name.001, .002, ...): 7-Zip opens .001 directly; or `copy /b` to join."""
    parts = []
    with open(path, "rb") as f:
        i = 1
        while True:
            chunk_path = path.with_name(f"{path.name}.{i:03d}")
            written = 0
            with open(chunk_path, "wb") as out:
                while written < PART_SIZE:
                    block = f.read(min(1 << 24, PART_SIZE - written))
                    if not block:
                        break
                    out.write(block)
                    written += len(block)
            if written == 0:
                chunk_path.unlink()
                break
            parts.append(chunk_path)
            i += 1
    path.unlink()
    print(f"  split into {len(parts)} parts: {', '.join(p.name for p in parts)}")
    return parts


def wix(*args):
    run("dotnet", "tool", "run", "wix", *args)


def make_msi(edition: str) -> Path:
    msi = OUT / name(edition, "win64.msi")
    wix("build", WIX_DIR / "VoiceCleaner.wxs", WIX_DIR / "InstallDirUI.wxs",
        "-ext", "WixToolset.UI.wixext", "-ext", "WixToolset.Util.wixext", "-arch", "x64",
        "-d", f"Edition={edition}", "-d", f"Version={APP_VERSION}", "-d", f"SourceDir={dist_dir(edition)}",
        "-d", f"IconFile={ROOT / 'assets' / 'voicecleaner.ico'}",
        "-d", f"BannerBmp={WIX_DIR / 'banner.bmp'}", "-d", f"DialogBmp={WIX_DIR / 'dialog.bmp'}",
        "-intermediateFolder", ROOT / "build" / f"wix-{edition}", "-o", msi)
    for junk in OUT.glob("*.wixpdb"):
        junk.unlink()
    return msi


def make_web_installer(gpu_msi: Path) -> Path:
    exe = OUT / name("gpu", "web.exe")
    wix("build", WIX_DIR / "Bundle.wxs", "-ext", "WixToolset.BootstrapperApplications.wixext", "-arch", "x64",
        "-d", f"Version={APP_VERSION}", "-d", f"MsiFile={gpu_msi}",
        "-d", f"BaseUrl=https://github.com/{REPO}/releases/download/{TAG}/",
        "-d", f"IconFile={ROOT / 'assets' / 'voicecleaner.ico'}",
        "-d", f"LogoFile={WIX_DIR / 'bundle_logo.png'}",
        "-intermediateFolder", ROOT / "build" / "wix-bundle", "-o", exe)
    for junk in OUT.glob("*.wixpdb"):
        junk.unlink()
    return exe


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 22), b""):
            h.update(block)
    return h.hexdigest()


def write_checksums():
    lines = [f"{sha256(p)}  {p.name}" for p in sorted(OUT.iterdir())
             if p.is_file() and p.name != "SHA256SUMS.txt" and not p.name.startswith("RELEASE_NOTES")]
    (OUT / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


