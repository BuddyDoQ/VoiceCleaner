def changelog_entry(version: str) -> str:
    """The CHANGELOG.md section for ``version`` (without its heading)."""
    try:
        text = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    except OSError:
        return ""
    import re

    m = re.search(rf"^## {re.escape(version)}\s*$(.*?)(?=^## |\Z)", text, flags=re.M | re.S)
    return m.group(1).strip() if m else ""


def macos_section(body: str) -> str:
    """The "## macOS ..." section (to the end) of existing release notes, or ""."""
    import re

    m = re.search(r"^## macOS\b", body.replace("\r\n", "\n"), flags=re.M)
    return body.replace("\r\n", "\n")[m.start():].strip() + "\n" if m else ""


def publish():
    assets = [p for p in sorted(OUT.iterdir()) if p.is_file() and not p.name.startswith("RELEASE_NOTES")]
    too_big = [p.name for p in assets if p.stat().st_size >= 2 * 1024**3]
    if too_big:
        sys.exit(f"Files over GitHub's 2 GB limit: {too_big}")
    run(GH, "auth", "status")
    exists = subprocess.run([GH, "release", "view", TAG, "-R", REPO], capture_output=True).returncode == 0
    if exists:
        run(GH, "release", "upload", TAG, *assets, "-R", REPO, "--clobber")
        notes = OUT / "RELEASE_NOTES.md"
        current = subprocess.run([GH, "release", "view", TAG, "-R", REPO, "--json", "body", "--jq", ".body"],
                                 capture_output=True, text=True, encoding="utf-8").stdout
        mac = macos_section(current)
        if mac:  # the Mac build is published from a Mac (tools/build_mac.py); keep its section
            notes = OUT / "RELEASE_NOTES-combined.md"
            notes.write_text((OUT / "RELEASE_NOTES.md").read_text(encoding="utf-8").rstrip() + "\n\n---\n\n" + mac,
                             encoding="utf-8")
        run(GH, "release", "edit", TAG, "-R", REPO, "--notes-file", notes)
    else:
        run(GH, "release", "create", TAG, *assets, "-R", REPO, "--target", "main",
            "--title", f"VoiceCleaner {APP_VERSION}", "--notes-file", OUT / "RELEASE_NOTES.md")
    print(f"\nPublished https://github.com/{REPO}/releases/tag/{TAG}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-tests", action="store_true")
    ap.add_argument("--skip-build", action="store_true")
    ap.add_argument("--only", choices=["standard", "gpu"])
    ap.add_argument("--publish", action="store_true", help="upload to GitHub after building")
    ap.add_argument("--publish-only", action="store_true")
    a = ap.parse_args()
    if a.publish_only:
        publish()
        return
    editions = [a.only] if a.only else ["standard", "gpu"]
    if not a.skip_build:
        write_version_info()
        run(sys.executable, "tools/make_installer_art.py")
        for i, ed in enumerate(editions):
            build_edition(ed, skip_tests=a.skip_tests or i > 0)  # run the tests once
    if OUT.exists() and not a.only:
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True, exist_ok=True)
    run("dotnet", "tool", "restore")
    for ext in ("WixToolset.UI.wixext/5.0.2", "WixToolset.Util.wixext/5.0.2",
                "WixToolset.BootstrapperApplications.wixext/5.0.2"):
        wix("extension", "add", ext)
    for ed in editions:
        make_zip(ed)
        msi = make_msi(ed)
        if ed == "gpu":
            make_web_installer(msi)
    write_checksums()
    write_notes()
    for p in sorted(OUT.iterdir()):
        print(f"  {p.stat().st_size / 1e6:9.1f} MB  {p.name}")
    print(f"\nRelease {APP_VERSION} ready in {OUT}")
    if a.publish:
        publish()


if __name__ == "__main__":
    os.chdir(ROOT)
    main()
